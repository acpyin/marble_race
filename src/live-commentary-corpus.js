export function stageDetail(stage){
  const number=parseInt(stage,10),label=stage.replace(/^\d+\s*·\s*/,'');
  if(number===3)return openingDetails[label]||stageDetails[2];
  if(number>=30&&number<=37){
    if(label.includes('乱石')||label.includes('异形'))return '三列高低错位的木质几何块迎面而来，选手要从缝隙中找出路线。';
    if(label.includes('S形')||label.includes('S槽')||label.includes('蛇槽'))return '抬高木板中的连续S槽反复回弯，守住槽线才能稳稳带走速度。';
    if(label.includes('交叉漏斗'))return '玻璃管与金属管交叉收口，一道接一道的漏斗可能重新排位。';
    if(label.includes('转轮')||label.includes('拨杆')||label.includes('旋杆'))return '双列旋杆改变通过时机，四排之后再看前后差距。';
    if(label.includes('波浪')||label.includes('汇流'))return '双道起伏后重新汇流，出口的位置比眼下的并排更重要。';
    return '这一组障碍接连改变通路，先看球流怎样走出弯道。';
  }
  if(number===38)return '拨杆在冲刺段前方，过关后还有一截空道通向收集口。';
  if(number===39)return '球陆续进入排次槽，最终次序要等最后一颗入槽才确定。';
  return stageDetails[number-1];
}

