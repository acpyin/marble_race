import assert from 'node:assert/strict';
import {VoiceCommentary,chooseChineseVoice,voiceGender,speechMood} from '../src/voice-commentary.js';
const voices=[{name:'Microsoft Kangkang',lang:'zh-CN',voiceURI:'male'},{name:'Microsoft Huihui',lang:'zh-CN',voiceURI:'female'},{name:'English',lang:'en-US',voiceURI:'english'}];
assert.equal(voiceGender(chooseChineseVoice(voices,'male',()=>0)),'male');
assert.equal(voiceGender(chooseChineseVoice(voices,'female',()=>0)),'female');
assert.equal(chooseChineseVoice([voices[1]],'male',()=>0),voices[1]);
assert.equal(chooseChineseVoice([voices[2]],'male'),null);
assert.ok(speechMood('反超第一').rate>speechMood('暂时受阻').rate);
assert.ok(speechMood('冲线冠军').pitch>speechMood('保持领先').pitch);
const spoken=[];let cancellations=0,changed;
const synth={getVoices:()=>voices,addEventListener:(_,fn)=>changed=fn,speak:u=>spoken.push(u),cancel:()=>cancellations++};
class Utterance {constructor(text){this.text=text;}}
const voice=new VoiceCommentary({synth,Utterance,random:()=>0});
voice.startRace();voice.announce('正在领先');voice.announce('旧的追赶消息');voice.announce('最新反超消息');
assert.equal(spoken.length,1);spoken[0].onend();assert.equal(spoken[1].text,'最新反超消息');
voice.announce('冠军冲线',{priority:true});assert.equal(spoken.at(-1).text,'冠军冲线');
const count=spoken.length;voice.setPaused(true);voice.announce('暂停消息');assert.equal(spoken.length,count);
voice.setPaused(false);voice.setEnabled(false);voice.announce('静音消息');assert.equal(spoken.length,count);
assert.ok(cancellations>=3);voice.stop();
voice.setSettings({rate:1.25,choice:'voice:male'});voice.startRace();assert.equal(voice.voice.voiceURI,'male');
voice.setPaused(true);voice.setEnabled(false);voice.announce('漂亮的反超',{preview:true});
assert.equal(spoken.at(-1).rate,1.22*1.25);assert.equal(spoken.at(-1).voice,voices[0]);voice.stop();
voice.setPaused(false);voice.setEnabled(true);voice.startRace();
voice.announce('冠军确定',{priority:true,mood:'excited'});
voice.announce('第二名确定',{confirmed:true,mood:'celebrate'});
voice.announce('第三名确定',{confirmed:true,mood:'celebrate'});
voice.announce('赛况旧消息');voice.announce('赛况新消息');
assert.equal(voice.confirmedQueue.length,2);
spoken.at(-1).onend();assert.equal(spoken.at(-1).text,'第二名确定');
spoken.at(-1).onend();assert.equal(spoken.at(-1).text,'第三名确定');
spoken.at(-1).onend();assert.equal(spoken.at(-1).text,'赛况新消息');
assert.ok(speechMood('同一句话','excited').rate>speechMood('同一句话','analysis').rate);
assert.ok(speechMood('同一句话','excited').pitch>speechMood('同一句话','concerned').pitch);
voice.stop();
console.log('语音检查通过：音色、情绪参数、最新赛况、冠军优先、暂停静音及完赛确认按序保留');
